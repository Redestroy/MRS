#!/usr/bin/env python3
"""Writes viewer/src/FontData.h: printable ASCII of DejaVu Sans Mono as an 8-bit alpha atlas,
so the viewer needs no font file at run time (spec 17 §4).

usage: make_font.py <DejaVuSansMono.ttf> <size px> > FontData.h   (needs Pillow)
DejaVu fonts: Bitstream Vera licence with public-domain changes; embedding is allowed.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

path, size = sys.argv[1], int(sys.argv[2])
font = ImageFont.truetype(path, size)
ascent, descent = font.getmetrics()
w = round(font.getlength("M"))
h = ascent + descent
chars = [chr(c) for c in range(32, 127)]
atlas = Image.new("L", (w * len(chars), h), 0)
d = ImageDraw.Draw(atlas)
for i, ch in enumerate(chars):
    d.text((i * w, 0), ch, font=font, fill=255)
px = list(atlas.tobytes())
print("#pragma once")
print("// Generated by viewer/tools/make_font.py from DejaVu Sans Mono %d px; do not edit." % size)
print("// DejaVu fonts: Bitstream Vera licence with public-domain changes (embedding allowed).")
print("namespace MRS {\n\tnamespace Viewer {\n\t\tnamespace FontData {")
print("\t\t\tconstexpr unsigned kGlyphW = %d, kGlyphH = %d, kFirst = 32, kCount = %d;" % (w, h, len(chars)))
print("\t\t\t// Row-major alpha, kCount glyphs side by side.")
print("\t\t\tconstexpr unsigned char kAlpha[] = {")
row = []
for k, v in enumerate(px):
    row.append(str(v))
    if len(row) == 40:
        print("\t\t\t    " + ",".join(row) + ",")
        row = []
if row:
    print("\t\t\t    " + ",".join(row) + ",")
print("\t\t\t};\n\t\t}\n\t}\n}")

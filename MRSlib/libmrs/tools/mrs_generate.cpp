// mrs_generate: turns operator geometry (GeoJSON) into a timeline of tasks (spec 11 §4.3).
// Usage: mrs_generate <features.geojson> <mission header .mrs> [--at SECONDS] [--land r1,r2,...]
//                     [--issuer op] [--first N]
//        mrs_generate delivery <packages> <sources.csv> <destinations.csv> [--seed S] [--zones]
//                     [--at SECONDS] [--issuer op] [--first N] [--manifest FILE] [--zones-out FILE]
// The delivery form (spec 18 §5) reads one point per line, "x,y" or "x,y,z" (ENU, m; lines starting
// with # are skipped), writes the timeline to standard output, the manifest CSV to --manifest and
// the zones (id,x,y,z,radius,hold_x,hold_y) to --zones-out.
// Each feature's "task" property picks the generator (spec 11 §4.2). The timeline goes to
// standard output; every task is dispatched at --at (default 1 s).
#include <cstdlib>
#include <fstream>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>

#include "mrs/generators/Generators.h"
#include "mrs/protocol/Parser.h"

using namespace MRS;

namespace {
	std::string ReadFile(const std::string& path) {
		std::ifstream in(path, std::ios::binary);
		if (!in) throw std::runtime_error("cannot open " + path);
		std::stringstream s;
		s << in.rdbuf();
		return s.str();
	}

	std::vector<Generators::Point> ReadPoints(const std::string& path) {
		std::vector<Generators::Point> out;
		std::stringstream in(ReadFile(path));
		std::string line;
		while (std::getline(in, line)) {
			if (!line.empty() && line.back() == '\r') line.pop_back();
			if (line.empty() || line[0] == '#') continue;
			std::stringstream ls(line);
			std::string cell;
			std::vector<double> v;
			while (std::getline(ls, cell, ',')) v.push_back(std::stod(cell));
			if (v.size() < 2 || v.size() > 3) throw std::runtime_error(path + ": expected x,y or x,y,z in \"" + line + "\"");
			out.push_back({v[0], v[1], v.size() == 3 ? v[2] : 0.0});
		}
		if (out.empty()) throw std::runtime_error(path + ": no points");
		return out;
	}

	void WriteFile(const std::string& path, const std::string& text) {
		std::ofstream out(path, std::ios::binary);
		if (!out) throw std::runtime_error("cannot write " + path);
		out << text;
	}

	int Delivery(int argc, char** argv) {
		if (argc < 5) {
			std::cerr << "usage: mrs_generate delivery <packages> <sources.csv> <destinations.csv> [--seed S] [--zones] [--at SECONDS]"
			             " [--issuer op] [--first N] [--manifest FILE] [--zones-out FILE]\n";
			return 2;
		}
		Generators::DeliveryOptions o;
		double at = 1.0;
		std::string issuer = "op", manifest, zones_out;
		int first = 1;
		for (int k = 5; k < argc; ++k) {
			const std::string a = argv[k];
			if (a == "--zones") {
				o.zones = true;
				continue;
			}
			if (k + 1 >= argc) throw std::runtime_error("missing value after " + a);
			const std::string v = argv[++k];
			if (a == "--seed") o.seed = std::stoull(v);
			else if (a == "--at") at = std::stod(v);
			else if (a == "--issuer") issuer = v;
			else if (a == "--first") first = std::stoi(v);
			else if (a == "--manifest") manifest = v;
			else if (a == "--zones-out") zones_out = v;
			else throw std::runtime_error("unknown option " + a);
		}
		const auto job = Generators::DeliveryTasks(std::stoi(argv[2]), ReadPoints(argv[3]), ReadPoints(argv[4]), o, issuer, first);
		std::vector<std::pair<double, Protocol::Record>> entries;
		for (const auto& t : job.tasks) entries.push_back({at, t});
		std::cout << Generators::Timeline(entries, "Generated by mrs_generate delivery (spec 18 §5).");
		if (!manifest.empty()) WriteFile(manifest, Generators::ManifestCsv(job));
		if (!zones_out.empty()) {
			std::ostringstream z;
			z << "id,x,y,z,radius,hold_x,hold_y\n";
			for (const auto& d : job.zones)
				z << d.id << "," << d.centre[0] << "," << d.centre[1] << "," << d.centre[2] << "," << d.radius << "," << d.hold[0] << "," << d.hold[1] << "\n";
			WriteFile(zones_out, z.str());
		}
		return 0;
	}

	double NumOf(const Protocol::Field& f) { return f.type == Protocol::FieldType::Int ? static_cast<double>(f.i) : f.n; }
}

int main(int argc, char** argv) {
	if (argc >= 2 && std::string(argv[1]) == "delivery") {
		try {
			return Delivery(argc, argv);
		} catch (const std::exception& e) {
			std::cerr << e.what() << "\n";
			return 1;
		}
	}
	if (argc < 3) {
		std::cerr << "usage: mrs_generate <features.geojson> <mission header .mrs> [--at SECONDS] [--land r1,r2,...] [--issuer op] [--first N]\n";
		return 2;
	}
	try {
		Generators::GeoJsonOptions o;
		double at = 1.0;
		for (int k = 3; k < argc; ++k) {
			const std::string a = argv[k];
			if (k + 1 >= argc) throw std::runtime_error("missing value after " + a);
			const std::string v = argv[++k];
			if (a == "--at") at = std::stod(v);
			else if (a == "--issuer") o.issuer = v;
			else if (a == "--first") o.first_id = std::stoi(v);
			else if (a == "--land") {
				std::stringstream s(v);
				std::string r;
				while (std::getline(s, r, ',')) o.land_robots.push_back(r);
			} else throw std::runtime_error("unknown option " + a);
		}
		auto header = Protocol::Parse(ReadFile(argv[2]));
		if (!header.Ok()) throw std::runtime_error(std::string("mission header: ") + header.error->message);
		const Protocol::Record* h = nullptr;
		for (const auto& r : header.document.records)
			if (r.code == "H_M") h = &r;
		if (!h) throw std::runtime_error(std::string("no H_M record in ") + argv[2]);
		const Environment::GeoReference geo(NumOf(h->fields.at(1)), NumOf(h->fields.at(2)), NumOf(h->fields.at(3)));
		const auto features = Generators::ReadGeoJson(ReadFile(argv[1]), geo);
		std::vector<std::pair<double, Protocol::Record>> entries;
		for (auto& t : Generators::TasksFromGeoJson(features, o)) entries.push_back({at, std::move(t)});
		std::cout << Generators::Timeline(entries, std::string("Generated by mrs_generate from ") + argv[1] + " (spec 11 §4).");
	} catch (const std::exception& e) {
		std::cerr << e.what() << "\n";
		return 1;
	}
	return 0;
}
